//! 会话应用服务。
//!
//! 这一层回答的是**业务问题**：这个会话是不是他的、界面该显示哪几条、
//! 这一轮能不能开跑。它上面是 HTTP（`crate::serve`），下面是 SQL
//! （`crate::store`）。
//!
//! 为什么要单独一层，而不是让 HTTP handler 直接查库：
//!
//!   1. **归属检查和「未找到」的口径只写一遍。** 「不是你的会话 = 未找到」
//!      这条规则散落在每个 handler 里的话，迟早有一个新接口忘了，而忘了
//!      的表现是越权读到别人的数据——不报错，安静地出事。
//!
//!   2. **网页和命令行走同一个入口。** 设计文档第 12 节的第 4 条不变量。
//!      两边各写一套准入规则，就会出现「网页拦得住、命令行拦不住」。
//!
//!   3. **对外的数据形状不等于数据库的行。** `sessions` 表有 user_id、
//!      deleted_at、creation_request_id，这些不该出现在给浏览器的 JSON 里。
//!      这一层负责把行翻译成 DTO，让表结构改动不会直接漏到接口上。

